def book(cover, edge, back):
    """The closed book in a cover ramp of three (shade, face, lit)."""
    return grid(BOOK, {"a": edge, "o": edge, "k": back, "P": PAGES[1], "p": PAGES[0], "Q": PAGES[2], "q": PAGES[1]},
                ramp=Ramp(cover))


