def done_item(name):
    """name with its article, or a bare name that gets "a" or "an"."""
    if not name.startswith(("a ", "an ")):
        name = ("an " if name[0] in "AEIOU" else "a ") + name
    return "This quest completes by itself as soon as you have %s in your inventory." % name


def done_check(when):
    return "Click the checkmark above once %s." % when


