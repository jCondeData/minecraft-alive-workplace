def main():
    for name, versions in ITEMS.items():
        folder = OUT / name
        folder.mkdir(parents=True, exist_ok=True)
        for ver, (draw, _) in versions.items():
            path = draw().save(folder / f"{ver}.png")
            print("wrote", path.relative_to(REPO))
        captions = {ver: caption for ver, (_, caption) in versions.items()}
        (folder / "captions.json").write_text(json.dumps(captions, indent=2) + "\n")


if __name__ == "__main__":
    main()
