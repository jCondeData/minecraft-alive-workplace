# --- Shared colours ---------------------------------------------------------------------------------------------------
B = {"a": BLUE.outline_light, "d": BLUE.outline_dark}          # the blueprint outline pair
EDGE = "#78a4dc"                                                # the cut edge of rolled blueprint paper
STRING = {"w": "#ecebe4"}                                       # cotton string
IRON = {"I": "#d8d8d8", "i": "#a8a8a8", "j": "#727272", "k": "#444444", "K": "#2b2b2b"}   # vanilla iron
OAK = {"P": "#c29d62", "p": "#af8f55", "q": "#967441", "A": STICK.outline_light, "E": STICK.outline_dark}
BRASS = {"Y": GOLD[3], "y": GOLD[2], "z": GOLD[1], "o": GOLD.outline_light, "O": GOLD.outline_dark}
PA = {"a": PARCHMENT.outline_light, "d": PARCHMENT.outline_dark}


def bp(art, legend=None):
    """A grid in the blueprint ramp: digits 0-3 are BLUE, a/d its outline pair."""
    return grid(art, dict(B, **(legend or {})), ramp=BLUE)


def pm(art, legend=None):
    """A grid in the parchment ramp: digits 0-3 are PARCHMENT, a/d its outline pair."""
    return grid(art, dict(PA, **(legend or {})), ramp=PARCHMENT)


