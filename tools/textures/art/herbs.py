"""The Sickness's eight far herbs and the Three-Herb Tonic (ROADMAP 31.17).

Each herb is drawn the way vanilla draws its flowers: one 16x16 texture used by the cross model and as the item, no
outline, a one-pixel stem in vanilla's flower greens (sampled from the poppy, cornflower and allium) that touches the
bottom row, and a head of three or four shades lit from the top-left. Each one's shape is its own at 16 px:

- Frostbloom: two pale blue bells hanging from an arched stem, with frosted blue-green leaves (snowy lands).
- Sunthistle: a round spiky yellow head on grey-green spiny leaves (deserts).
- Mirewort: three reedy blades with purple buds along the tallest (swamps).
- Peakmoss: a low silver-green tuft, wider than tall (the peaks).
- Jungle Orchid: a wide magenta orchid with a pale lip on a leaning stem (jungles).
- Sea Lavender: a branching spray of tiny lilac flowers (shores).
- Glowcap: a pale glowing mushroom with a smaller one at its foot, drawn like vanilla's mushrooms (dark forests).
- Petal Balm: a low herb whose leaves are pink, like the cherry grove's petals (cherry groves).

The Three-Herb Tonic is a round-bellied flask in vanilla's glass and cork (the same as the tonics of 30.15) holding a
green tonic, with three leaves tied round its neck.
"""
