def sheet(ramp, art=SHEET):
    """A sheet in a ramp of four (shade, face... lit) with its outline pair."""
    return grid(art, {"a": ramp.outline_light, "d": ramp.outline_dark}, ramp=Ramp(list(ramp)[-4:]))


def blank_blueprint():
    """An empty sheet of blueprint paper, plain like vanilla's empty map (a blind test read it as blue paper with or
    without a drafting border, so it stays empty as asked)."""
    return [sheet(BLUE).save(item("blank_blueprint"))]


