# --- Delivery Note ----------------------------------------------------------------------------------------------------
def fold(s, ramp, crease):
    """Folds a sheet across its long axis: the half below-left of the crease line x - y = crease drops one shade."""
    cols = [tuple(int(v) for v in c) for c in ramp]
    for y in range(s.h):
        for x in range(s.w):
            c = tuple(int(v) for v in s.get(x, y))
            if x - y < crease and c in cols[1:]:
                s.put(x, y, cols[cols.index(c) - 1])
    return s


