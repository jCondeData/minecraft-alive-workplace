# --- Quarry marker and scan tool: the stick convention (handle at the bottom-left, head at the top-right) ----------
def pad(art, legend, ramp=None):
    """A 16x16 sprite from an ASCII block; missing rows at the bottom are transparent."""
    rows = [r.strip() for r in art.strip().split("\n")]
    rows = [r.ljust(16, ".") for r in rows] + ["." * 16] * (16 - len(rows))
    assert all(len(r) == 16 for r in rows) and len(rows) == 16, "a row wider than 16, or more than 16 rows"
    return Sprite.from_ascii("\n".join(rows), legend, ramp)


