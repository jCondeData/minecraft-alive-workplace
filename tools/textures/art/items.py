def on(base, art, legend):
    """Paints an overlay drawn as ASCII onto a sprite: '.' leaves the pixel below, other letters come from `legend`
    (a colour with alpha 0 punches a hole)."""
    rows = [r.strip() for r in art.strip("\n").split("\n")]
    for y, row in enumerate(rows):
        for x, ch in enumerate(row):
            if ch not in ". ":
                base.put(x, y, legend[ch])
    return base


