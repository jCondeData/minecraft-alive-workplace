def blank_blueprint_v2():
    """Two sheets, one lying on the other (paper and blue dye make two)."""
    under = Ramp([BLUE[0], BLUE[0], BLUE[1], BLUE[2]], outline=(BLUE.outline_light, BLUE.outline_dark))
    s = Sprite()
    s.paste(sheet(under, SMALL_SHEET), 1, 5)        # the lower sheet, a step darker in the upper one's shade
    s.paste(sheet(BLUE, SMALL_SHEET), -1, 2)
    return s


