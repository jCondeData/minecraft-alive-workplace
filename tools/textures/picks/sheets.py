"""Alternative icons for the sheet items, for the owner to pick from: three new versions (v2, v3, v4) of the blueprint,
the blank blueprint, the shape planner and the patrol map. v1 is the current icon (tools/textures/art/items.py).

Every version is built around its own idea (a pose, an object or a composition), each from vanilla's family for that
kind of thing: sheets on the diagonal like the map and paper, a roll, a clipboard, a compass case like vanilla's, drafting
tools drawn like vanilla's tools. The blueprint family keeps the BLUE ramp of items.py; the patrol map its PARCHMENT.

    python3 tools/textures/picks/sheets.py      writes build/texture-picks/<item>/v2.png .. v4.png + captions.json
"""
