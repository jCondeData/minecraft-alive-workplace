"""The mod's item icons, each drawn as a member of its vanilla family (owner, 2026-09-29: "make the book match the
other books in style ... if you want to make a tool, try and match the style of other tools"):

- sheets lying on the diagonal like the map and paper: blank blueprint, blueprint, shape planner, patrol map,
  delivery note, travel ticket;
- the book pose: village ledger;
- the name tag's pose: price tag;
- the stick convention of tools (handle at the bottom-left, head at the top-right): field and quarry markers,
  rally banner, scan tool;
- the minecart's 3/4 view: settler's wagon.

Colours are sampled from vanilla's neighbours; every shape is drawn here."""
