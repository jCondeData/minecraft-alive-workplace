"""The questbook: one story in order, by village rank. Facts come from docs/guide/ (the player guide) and the code.

Each chapter has a spine: its quests that aren't optional, in order, each depending on the one before (the first on the
last core spine quest of the chapter before). Side quests are optional and branch off the spine; generate.py lays the
spine out left to right and the side quests above and below it.

A quest: key (stable: its id is a hash of it, never rename one that has shipped), title, desc (lines; "" is a blank
line), tasks, rewards, deps (keys in this chapter, or "chapter:key"), and optionally subtitle, icon, optional (a side
quest: doesn't count toward finishing the chapter), final (the chapter's big last quest), milestone (M27 to M35: left out
of the chapter until that expansion is switched on) and needs (mods it needs, comma-separated: left out without them).
The quests after a quest that is left out hang on the one before it, so the spine still reads in order.

Tasks: ("item", id[, count]), ("check", "what to do"), ("advancement", id), ("kill", entity, count),
("observe", block, "what to look at"). Rewards: ("item", id[, count]), ("xp", points), ("unlock", blueprint id): the build
joins the Blueprint Table of the player's village (26.10, /workplace unlock); a build quest whose next level starts locked
rewards that level. Emeralds and a little experience; nothing that skips the game. aliveworkplace:built/<blueprint> ticks when a builder finishes that blueprint;
aliveworkplace:village/<moment> when the village lives through it (generate.py's MOMENTS). A checkmark only where nothing
can be seen.

How a description reads (B150, owner 2026-10-16: "rewrite them so they make more sense"): the goal in one short
sentence; then exactly what to do, step by step, naming the real block, item or screen button; one line on why it
matters; and last, how the quest completes (by itself, or "Click the checkmark above once ..."). Plain words, short
sentences, "you". Every claim is checked against the code: never describe what the mod doesn't do.

A chapter's milestone keeps the whole chapter out until that expansion is switched on; needs lists the mods it needs
(comma-separated, or "-").
"""

E = "minecraft:emerald"
C = "cobblemon"


def em(n):
    return ("item", E, n)


def built(path):
    return ("advancement", "aliveworkplace:built/" + path)


def moment(name):
    return ("advancement", "aliveworkplace:village/" + name)


def build_steps(name, first=1):
    """Getting a starting blueprint built, step by step (Builders.MAX_SITE_DISTANCE 48, SupplyContainers.RADIUS 8)."""
    return ["%d. Right-click the Blueprint Table, pick the %s and press Get Blueprint. It uses one Blank Blueprint (craft paper and blue dye to get two)." % (first, name),
            "%d. Hold the blueprint and right-click the ground where the front should go, within 48 blocks of the Blueprint Table. The gold edge of the outline is the front." % (first + 1),
            "%d. Hold Shift over the blueprint to see what it needs. Put all of it in chests or barrels within 8 blocks of the Blueprint Table." % (first + 2),
            "%d. Right-click your Builder with the blueprint. They clear the spot and build it during the day." % (first + 3)]


def bought_steps(name, seller):
    """A blueprint that starts locked and is bought from a villager instead of taken at the Table."""
    return ["1. Buy the %s blueprint from %s: right-click them to see their trades." % (name, seller),
            "2. Hold the blueprint and right-click the ground where the front should go, within 48 blocks of your builder's Blueprint Table.",
            "3. Hold Shift over the blueprint to see what it needs. Put all of it in chests or barrels within 8 blocks of the Blueprint Table.",
            "4. Right-click your Builder with the blueprint."]


def upgrade_steps(name, base):
    """Building an upgrade over the finished building (BlueprintItem: an upgrade clicked onto its base lines up)."""
    return ["1. Right-click the Blueprint Table, pick %s and press Get Blueprint (it uses one Blank Blueprint)." % name,
            "2. Right-click the finished %s with it, without sneaking. The outline lines up exactly over the building." % base,
            "3. Hold Shift over the blueprint to see what it needs, and put it in chests within 8 blocks of the Blueprint Table.",
            "4. Right-click your Builder with it. They only build what's new."]


def builder_upgrade_steps(name, base):
    """An upgrade that isn't in the Table: the builder who finished the tier below sells it (UpgradeOffers)."""
    return ["1. The builder who finished your %s now sells the %s blueprint. Right-click them to trade for it." % (base, name),
            "2. Right-click the finished %s with it, without sneaking. The outline lines up exactly over the building." % base,
            "3. Hold Shift over the blueprint to see what it needs, and put it in chests within 8 blocks of the Blueprint Table.",
            "4. Right-click your Builder with it. They only build what's new."]


def job_steps(villager_by, item, job, step=None):
    """Giving a villager a job with an item (Stations.choose: within 4.5 blocks of a free workstation; switching between
    jobs other than the Builder is free, Retraining.applies). After build_steps, step is 5."""
    first = "Stand a villager right next to the %s, hold %s and sneak-right-click the villager: they become a %s." % (villager_by, item, job)
    return [("%d. " % step if step else "") + first,
            "A villager who already took another job at that block works too: sneak-right-click them the same way."]


LOCKED = "Its name is gray at the Blueprint Table at first: it's locked. Pick it there and the line under its name says how to get it."


def done_built(name):
    return "This quest completes by itself when the builder finishes the %s." % name


WONDER_HOW = ("To raise it: on the hall's Wonders page, click its card once every line is ticked, then build it as in"
              " \"Your first Wonder\". A village raises one Wonder at a time.")

